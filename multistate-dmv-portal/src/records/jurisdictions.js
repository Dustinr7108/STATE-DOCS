/** State and city vital-records desks.
 * Mail addresses follow the 2026 Where-to-Write compilation used by county recorders.
 * A website link is not the same as a finished online order. Every desk below can be reached by mail.
 */

function office({ code, name, office, mail, phone, url, payableTo, paymentNote, inPerson, birth, death, marriage, divorce, counties, dmv }) {
  const stateBirth = {
    holder: "state",
    portal: "partial",
    since: birth?.since || "",
    localNote: birth?.localNote || "",
  };
  return {
    code,
    name,
    vital: {
      office,
      mail,
      phone,
      url,
      payableTo: payableTo || office.split("\n")[0],
      paymentNote: paymentNote || "Send a check or money order for the current certified-copy fee. Do not send cash. If the fee changed, ask the office to bill the difference or return the payment with the current fee.",
      inPerson: inPerson || "",
    },
    records: {
      birth: stateBirth,
      death: {
        holder: death?.holder || "state",
        portal: death?.portal || "partial",
        since: death?.since || birth?.since || "",
        localNote: death?.localNote || birth?.localNote || "",
      },
      marriage: {
        holder: marriage?.holder || "both",
        portal: marriage?.portal || (marriage?.holder === "county" ? "none" : "partial"),
        since: marriage?.since || "",
        localNote: marriage?.localNote || "If the state index does not have the license, the county or town clerk where it was issued still has it.",
      },
      divorce: {
        holder: divorce?.holder || "court",
        portal: divorce?.portal || "none",
        since: divorce?.since || "",
        localNote: divorce?.localNote || "A divorce decree is a court record. Mail the clerk of the court that granted it. The state vital-records office can often tell you which court, even when it cannot sell the decree.",
      },
      adoption: {
        holder: "state",
        portal: "none",
        since: birth?.since || "",
        localNote: "Order the birth certificate in the current legal name by mail. If a pre-adoption record is sealed, the office must say so in writing and point to the court or adult-adoptee process. This service does not unseal a court record.",
      },
      driver: {
        holder: "dmv",
        portal: dmv?.portal || "partial",
        since: "",
        localNote: dmv?.localNote || "You can request your own driver record. The state still checks identity under the Driver's Privacy Protection Act.",
      },
    },
    counties: counties || [],
    dmv: {
      office: dmv?.office || `${name} motor vehicle records unit`,
      mail: dmv?.mail || "",
      phone: dmv?.phone || "",
      url: dmv?.url || "https://www.usa.gov/motor-vehicle-services",
      payableTo: dmv?.payableTo || `${name} Department of Motor Vehicles`,
    },
  };
}

