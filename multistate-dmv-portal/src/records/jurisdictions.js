const byCode = new Map(JURISDICTIONS.map((item) => [item.code, item]));

export function listJurisdictions() {
  return JURISDICTIONS.map((item) => ({
    code: item.code,
    name: item.name,
    phone: item.vital.phone,
    url: item.vital.url,
    countyCount: item.counties.length,
    records: Object.fromEntries(
      Object.entries(item.records).map(([key, spec]) => [key, { holder: spec.holder, portal: spec.portal, since: spec.since }])
    ),
  }));
}

export function getJurisdiction(code) {
  if (!code) return null;
  return byCode.get(String(code).toUpperCase()) || null;
}

