export const STATE_CODES = US_STATES.map((state) => state.code);

export const STATE_LABELS = Object.fromEntries(US_STATES.map((state) => [state.code, state.name]));

export function stateByCode(code) {
  if (!code) return null;
  return US_STATES.find((state) => state.code === String(code).trim().toUpperCase()) || null;
}

export function normalizeState(value) {
  if (value == null || String(value).trim() === "") return null;
  const raw = String(value).trim();
  const byCode = stateByCode(raw);
  if (byCode) return byCode.code;
  const byName = US_STATES.find((state) => state.name.toLowerCase() === raw.toLowerCase());
  return byName ? byName.code : null;
}
